/// A logical UI input event.
///
/// Each variant carries the data needed to describe one user action, without a
/// target widget: routing and hit testing are the responsibility of the
/// receiver, typically the widget tree in [`crate::widgets`]. Pointer
/// coordinates and scroll deltas use the same logical-pixel convention as the
/// callbacks on [`crate::window::WindowDelegate`].
///
/// # Examples
///
/// ```
/// use cadmium::events::{Key, Modifiers, PointerButton, UiEvent};
///
/// let click = UiEvent::PointerDown {
///     x: 24.0,
///     y: 48.0,
///     button: PointerButton::Left,
/// };
/// let UiEvent::PointerDown { x, y, .. } = click else {
///     panic!("expected a pointer-down event");
/// };
/// assert_eq!((x, y), (24.0, 48.0));
///
/// let enter = UiEvent::KeyDown {
///     key: Key::Enter,
///     modifiers: Modifiers::default(),
/// };
/// assert!(matches!(enter, UiEvent::KeyDown { .. }));
/// ```
#[derive(Debug, Clone)]
pub enum UiEvent {
    /// A mouse button was pressed.
    PointerDown {
        /// Horizontal pointer position in logical pixels.
        x: f32,
        /// Vertical pointer position in logical pixels.
        y: f32,
        /// Button that was pressed.
        button: PointerButton,
    },
    /// A mouse button was released.
    PointerUp {
        /// Horizontal pointer position in logical pixels.
        x: f32,
        /// Vertical pointer position in logical pixels.
        y: f32,
        /// Button that was released.
        button: PointerButton,
    },
    /// The pointer moved to a new position.
    PointerMove {
        /// Horizontal pointer position in logical pixels.
        x: f32,
        /// Vertical pointer position in logical pixels.
        y: f32,
    },
    /// The mouse wheel moved.
    Scroll {
        /// Horizontal scroll delta in logical pixels.
        delta_x: f32,
        /// Vertical scroll delta in logical pixels.
        delta_y: f32,
    },
    /// A widget or window gained keyboard focus.
    FocusGained,
    /// A widget or window lost keyboard focus.
    FocusLost,
    /// A keyboard key was pressed.
    KeyDown {
        /// The key that was pressed.
        key: Key,
        /// Modifier keys held at the time of the press.
        modifiers: Modifiers,
    },
}

/// Tracks keyboard focus, hover and capture targets, and tab order.
///
/// The struct is plain data; only [`Self::set_focus`], [`Self::cycle_next`] and
/// [`Self::cycle_prev`] mutate it, and they change [`Self::focused`] alone.
/// `focus_order` is populated by the code that owns the widget tree, such as
/// [`crate::widgets::WidgetArena`]; `hovered` and `captured` are plain storage
/// for input code. Cycling wraps
/// around the ends of `focus_order` and returns [`None`] when the order is
/// empty. Methods do not emit focus events or request redraws.
///
/// # Examples
///
/// ```
/// use cadmium::events::{FocusManager, WidgetId};
/// use slotmap::SlotMap;
///
/// let mut nodes: SlotMap<WidgetId, ()> = SlotMap::with_key();
/// let first = nodes.insert(());
/// let second = nodes.insert(());
///
/// let mut focus = FocusManager::new();
/// focus.focus_order = vec![first, second];
///
/// assert_eq!(focus.cycle_next(), Some(first));
/// assert_eq!(focus.cycle_next(), Some(second));
/// assert_eq!(focus.cycle_next(), Some(first)); // wraps around
/// assert_eq!(focus.cycle_prev(), Some(second));
/// assert!(focus.set_focus(None));
/// assert!(!focus.set_focus(None)); // no change
/// ```
#[derive(Default)]
pub struct FocusManager {
    /// Widget that currently has keyboard focus, if any.
    pub focused: Option<WidgetId>,
    /// Widget currently under the pointer, if any.
    ///
    /// `FocusManager` does not update this field itself; the input code that
    /// hit-tests pointer movement sets it.
    pub hovered: Option<WidgetId>,
    /// Widget that has captured pointer input, if any.
    ///
    /// The field is intended for the widget that should keep receiving pointer
    /// events after the pointer leaves its bounds; `FocusManager` only stores
    /// the value and does not manage capture itself.
    pub captured: Option<WidgetId>,
    /// Widgets in keyboard tab order, from first to last.
    ///
    /// [`Self::cycle_next`] and [`Self::cycle_prev`] use this order. Duplicate
    /// entries cause the same widget to appear more than once in the cycle.
    pub focus_order: Vec<WidgetId>,
}

impl FocusManager {
    /// Creates an empty focus manager with no targets and an empty tab order.
    pub fn new() -> Self {
        Self::default()
    }

    /// Sets the focused widget and reports whether the focus changed.
    ///
    /// Passing [`None`] clears focus. Returns `false` when `id` is already the
    /// focused widget, which lets callers avoid redundant work; no events are
    /// generated by this method.
    pub fn set_focus(&mut self, id: Option<WidgetId>) -> bool {
        if self.focused == id {
            return false;
        }
        self.focused = id;
        true
    }

    /// Moves focus to the next widget in [`Self::focus_order`] and returns it.
    ///
    /// Wraps from the last entry back to the first. If focus is currently
    /// [`None`] or points to a widget absent from the order, the first entry is
    /// selected. Returns [`None`] without changing focus when the order is
    /// empty.
    pub fn cycle_next(&mut self) -> Option<WidgetId> {
        if self.focus_order.is_empty() {
            return None;
        }
        let next = match self
            .focused
            .and_then(|f| self.focus_order.iter().position(|&id| id == f))
        {
            Some(idx) => self.focus_order[(idx + 1) % self.focus_order.len()],
            None => self.focus_order[0],
        };
        self.focused = Some(next);
        Some(next)
    }

    /// Moves focus to the previous widget in [`Self::focus_order`] and returns
    /// it.
    ///
    /// Wraps from the first entry back to the last. If focus is currently
    /// [`None`] or points to a widget absent from the order, the last entry is
    /// selected. Returns [`None`] without changing focus when the order is
    /// empty.
    pub fn cycle_prev(&mut self) -> Option<WidgetId> {
        if self.focus_order.is_empty() {
            return None;
        }
        let len = self.focus_order.len();
        let prev = match self
            .focused
            .and_then(|f| self.focus_order.iter().position(|&id| id == f))
        {
            Some(idx) => self.focus_order[(idx + len - 1) % len],
            None => self.focus_order[len - 1],
        };
        self.focused = Some(prev);
        Some(prev)
    }
}

